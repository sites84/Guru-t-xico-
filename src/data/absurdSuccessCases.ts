/**
 * Retorna exatamente 6 cases de sucesso para o dia atual.
 * Baseado no epoch day (dias desde 1970) + dayOffset.
 * Com 42 cases (7 dias x 6 cases), garante que todos os 6 cases de um dia
 * são completamente diferentes dos cases do dia anterior e seguinte!
 */
export function getDailySuccessCases(dayOffset: number = 0): { dateString: string; cases: AbsurdSuccessCase[] } {
  const d = new Date();
  d.setDate(d.getDate() + dayOffset);
  const dateString = d.toISOString().slice(0, 10);
  const dayEpoch = Math.floor(d.getTime() / (1000 * 60 * 60 * 24));

  const total = ALL_ABSURD_SUCCESS_CASES.length; // 42
  const casesPerDay = 6;
  const startIndex = Math.abs(dayEpoch * casesPerDay) % total;

  const cases: AbsurdSuccessCase[] = [];
  for (let i = 0; i < casesPerDay; i++) {
    cases.push(ALL_ABSURD_SUCCESS_CASES[(startIndex + i) % total]);
  }

  return { dateString, cases };
}
